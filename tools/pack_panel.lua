--- Пакует файлы панели в один Lua-модуль.
---
--- Панель приезжает вместе с приложением: ни отдельного веб-сервера,
--- ни каталога со статикой, ни расхождения между версией панели и версией
--- кластера. Узел раздаёт её из памяти процесса тем же роком, что и код.
---
--- Запуск: tarantool tools/pack_panel.lua
---
--- Модуль пересобирается целиком: набор файлов панели — это один комплект,
--- и подкладывать в него по одному значит однажды получить страницу
--- от одной версии со сценарием от другой.

local fio = require('fio')

local files = dofile('tools/files.lua')

local SOURCE_DIR = 'panel'
local TARGET = 'tnt/admin/public/bundle.lua'

local parts = {
    '--- Файлы панели, упакованные в модуль.',
    '---',
    -- Каталог назван от корня пакета, а не репозитория: заголовок едет
    -- с модулем в установленный рок, и путь дерева разработки там никуда
    -- не ведёт.
    '--- Файл собран инструментом tools/pack_panel.lua из каталога panel пакета:',
    '--- править его руками бесполезно, правки затрёт следующая сборка.',
    '',
    'return {',
}

local packed = 0

for _, name in ipairs(files.list(SOURCE_DIR)) do
    -- Длинные скобки с уровнем: содержимое панели само содержит
    -- квадратные скобки, и обычная строка порвалась бы на первой же.
    local body = files.read(fio.pathjoin(SOURCE_DIR, name))

    table.insert(parts, ("    ['%s'] = [==[\n%s]==],"):format(name, body))
    packed = packed + 1
end

table.insert(parts, '}')
table.insert(parts, '')

files.write(TARGET, table.concat(parts, '\n'))

print(('Панель упакована: файлов %d → %s'):format(packed, TARGET))
