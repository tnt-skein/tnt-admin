--- Отказы панели: каталог, вид тела и ответ об отказе.
---
--- Вид отказа панель задаёт сама — своей функцией — и берёт для него
--- отдельный каталог, а не общий на приложение. Панель — это собранный JS:
--- он читает `error.message` и смотрит на код ответа, и настройка
--- приложения «отвечать по RFC 9457» сломала бы её молча. Через этот
--- каталог идёт всё: свои отказы панели, ответы ворот и раскатки, поломки,
--- пойманные перехватом, и отказы роутера — «нет такого адреса» и «сюда
--- так нельзя». Форма тела задана один раз, в виде. Клиентам она описана
--- схемой `Refusal` в описании API панели, и это второе описание
--- не расходится с первым молча: сверка описания прогоняет образцы отказов
--- через панель и сличает их тела со схемами. Всё, что панель кладёт
--- сверх вида, — разбор по полям, код ворот, фазу, оценку
--- и отчёт раскатки — дописывает одна функция `refuse`, после вида: это
--- не слова во фразе, а отдельные данные, и прятать их по имени поля,
--- как прячутся тайны в подстановках, нельзя.
---
--- Отдельным модулем, а не внутри HTTP-слоя: отказами отвечают
--- и обработчики панели (`tnt.admin.app.http.handlers.panel`), и маршруты журнала
--- аудита (`tnt.admin.app.http.handlers.audit`), и отбор узлов
--- (`tnt.admin.app.http.handlers.instances`), и слой прав
--- (`tnt.admin.app.http.middleware.can`), а каталог у них один — у панели
--- одна форма тела. Тем же видом отвечает и ядро: роль отдаёт его разделом
--- `http.error_view`, и отказы роутера — «нет такого адреса», «сюда так
--- нельзя» — и поломки приходят панели в её собственном теле.

local errors = require('tnt.error')
local router = require('tnt.router')

local Module = {}

--- Общее начало кодов отказа: по нему их узнают в журнале и в каталоге,
--- если панель поднимут рядом с другим приложением.
local CODE = 'admin.'

--- Отказы панели: код ответа, а под ним — имена отказов и слова, которые
--- увидит оператор.
---
--- Сгруппированы по коду ответа, а не по месту, где случаются: код — это
--- то, на что смотрит панель, и держать отказы рядом по коду значит видеть
--- сразу, чем панель вообще отвечает.
---
--- Слово источника идёт наружу как есть, когда он сказал его строкой,
--- и своё — когда смолчал: отказ без причины оператор читает как поломку
--- панели и жмёт кнопку снова. Так же идут слова ворот и раскатки. Наш
--- отказ говорит своим `message` — его писал разработчик. Чужая причина —
--- таблица, объект `box.error` — наружу не идёт вовсе: вместо неё своё
--- слово и опознаватель записи в журнале.
---
--- Группы 409 и 428 — ответы ворот и раскатки; почему именно эти коды,
--- объяснено у таблиц `GATE_REFUSAL` и `ROLLOUT_REFUSAL`
--- в `tnt.admin.app.http.handlers.panel`.
---@type table<integer, table<string, string>>
