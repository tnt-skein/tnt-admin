--- Вид отказа панели: ровно то тело, которое разбирает её JS.
---
--- Форма тела задана здесь: через этот вид идут и свои отказы панели,
--- и ответы ворот и раскатки, и поломки, и отказы роутера. Клиентам она
--- описана схемой `Refusal` в описании API панели, и сверка описания
--- сличает с ней тела отказов: поправили вид — правьте схему, иначе
--- сверка не пройдёт.
---@param err TntError
---@param _settings TntErrorSettings
---@return table
function Module.view(err, _settings)
    return {
        error = {
            status = err.status,
            message = err.message,
            -- Опознаватель есть только у происшествия: назвать его
            -- дежурному можно, а у ожидаемого отказа искать в журнале
            -- нечего.
            incident = err.incident,
        },
    }
end

--- Настройка каталога.
---
--- Тип назван вслух, а не снят обходом `---@type any`: он здесь
--- единственный в дереве образец настройки отказов, и проверка типов —
--- единственное, что сторожит обещание пакета «задавать настройки можно
--- по одной». Обход прятал бы правку, вернувшую обязательные поля.
---
--- Подписи здесь нет: ответы панели собирает `router.json`, а отказы,
--- которые собирает ядро, подписаны его настройкой. Вторая подпись,
--- записанная тут, не попала бы ни в один ответ и разошлась бы с первой
--- молча.
---@type TntErrorOptions
local PANEL_VIEW = { view = Module.view }

--- Каталог отказов панели.
---
--- Свой вид, а не RFC 9457 и не простой: JS панели читает
--- `error.message` и смотрит на `error.status`, и ни один готовый вид
--- такого тела не собирает. Каталог отдельный, а не общий на приложение,
--- по той же причине: настройка приложения «отвечать по RFC 9457»
--- сломала бы панель молча.
---
--- Открыт затем, что в нём же объявляют свой отказ ворота прав панели
--- (`tnt.admin.app.http.middleware.can`): общий каталог приложения им
--- не годится по той же причине.
Module.catalog = errors.registry(PANEL_VIEW)

local catalog = Module.catalog

--- Слово по умолчанию к каждому отказу.
---@type table<string, string>
local DEFAULT_REASON = {}

for status, kinds in pairs(REFUSALS) do
    for name, reason in pairs(kinds) do
        -- Строка собирается подстановкой: на место своего слова встаёт
        -- слово источника, а тайны из него вырезаются по дороге. Родовое
        -- имя остаётся своим — по RFC 9457 оно не меняется от случая
        -- к случаю.
        catalog:define(CODE .. name, { status = status, title = reason, message = '{reason}' })

        DEFAULT_REASON[name] = reason
    end
end

---@class TntAdminRefusal
---@field reason any Слово источника вместо своего: строка, наш отказ или чужая причина
---@field details table<string, any>|nil Что дописать под `error` рядом с фразой: разбор полей, код ворот, фаза
---@field attached table<string, any>|nil Что положить рядом с `error`: оценка, отчёт раскатки
---@field headers table<string, string>|nil Заголовки ответа

--- Отказ по объявленному имени с причиной, какой её назвал источник.
---
--- Причина бывает трёх родов, и наружу каждый идёт по-своему: разбирать
--- её по виду значения здесь приходится потому, что `tostring` таблицы
--- в подстановке уезжал оператору строкой `table: 0x...`.
---@param name string Имя отказа без общего начала кода
---@param reason any Что источник вернул вторым значением
---@return TntError
local function refusal_for(name, reason)
    local code = CODE .. name

    if reason == nil or type(reason) == 'string' then
        return catalog:new(code, { reason = reason or DEFAULT_REASON[name] })
    end

    if errors.code_of(reason) ~= nil then
        -- Наш отказ: его `message` написал разработчик, и показать его
        -- безопасно. Статус при этом остаётся панельным: коды ответа —
        -- договор панели с её JS, и 401 или 404 источника, поднятые
        -- наверх, JS прочёл бы как «не вошли» и «нет такого адреса».
        -- Причина остаётся под отказом для журнала, а опознаватель
        -- наследуется: о происшествии уже написано, и второй номер
        -- увёл бы дежурного к пустой записи.
        return catalog:wrap(reason, code, { reason = reason.message })
    end

    -- Чужая причина — таблица, отказ клиента HTTP, объект `box.error`:
    -- кто сочинил её текст, неизвестно, и наружу идут только своё слово
    -- и опознаватель, а сама причина — в журнал, где `internal` пишет её
    -- описанием: печатью, а простую таблицу — JSON без тайн. Через `of`
    -- её не провести: у отказа клиента HTTP целый `status` чужого
    -- сервера, и `of` принял бы его за отказ границы — без записи
    -- в журнал и с чужим словом наружу.
    return catalog:wrap(catalog:internal(reason), code, { reason = DEFAULT_REASON[name] })
end

--- Ответ об отказе по объявленному имени.
---
--- Тело собирает вид каталога, а довески дописываются после него, а не
--- подстановками в отказ. Подстановки проходят вырезание тайн, которое
--- прячет значение по имени ключа, а среди примет тайны есть `token`:
--- объяснение поля `confirm_token` ушло бы оператору словом «скрыто».
--- Да и не подстановки это: во фразу они не входят, это отдельные данные.
--- Каждый довесок описан полем схемы `Refusal` в описании API панели:
--- новый без строки в описании сверка описания не пропустит.
---
--- Ответ собирается `router.json`, а не `catalog:response`: тот отдаёт
--- тело уже строкой, дописать в которую нечего, а заголовки — например
--- срок `retry-after` — берёт из отказа, а не из вызова.
---@param name string Имя отказа без общего начала кода
---@param opts TntAdminRefusal|nil
---@return table
function Module.refuse(name, opts)
    local given = opts or {}
    local body, status = catalog:render(refusal_for(name, given.reason))

    -- Разбор по полям едет рядом с общей фразой, а не вместо неё: фразу
    -- панель показывает, а разметить поля формы может только по этому
    -- списку. Так же рядом с фразой едут код ворот и фаза раскатки.
    for key, value in pairs(given.details or {}) do
        body.error[key] = value
    end

    for key, value in pairs(given.attached or {}) do
        body[key] = value
    end

    return router.json(body, status, given.headers)
end

return Module
