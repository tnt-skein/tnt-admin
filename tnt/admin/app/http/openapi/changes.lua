--- Описание операций, которые меняют кластер или пускают в панель:
--- оценка и выполнение действия, показ и правка конфигурации, вход.
---
--- Часть описания API панели (`tnt.admin.app.http.openapi`): здесь только
--- слова и коды. Схемы тел запросов — формы `tnt.admin.app.data.requests`,
--- ответов — `tnt.admin.app.data.results`. Отказы ворот и раскатки
--- уточняют тело отказа панели: код ворот и фаза раскатки у них — одно
--- из названных, и сверка `make lint-api` проверяет это на образцах.

local refusal = require('tnt.admin.app.data.refusal')
local requests = require('tnt.admin.app.data.requests')
local results = require('tnt.admin.app.data.results')

--- Тело отказа панели.
local Refusal = refusal.Refusal

--- Тело отказа, в котором поле `error` уточнено.
---@param required string Какое поле `error` обязательно
---@param values string[] Каким оно бывает
---@param extra table|nil Что ещё уточнить в теле
---@return table
local function refined(required, values, extra)
    local refinement = extra or {}

    refinement.properties = {
        error = { required = { required }, properties = { [required] = { enum = values } } },
    }

    return { allOf = { Refusal, refinement } }
end

