--- Описание операций журнала аудита: выгрузка потоком и проверка цепочки.
---
--- Часть описания API панели (`tnt.admin.app.http.openapi`): здесь только
--- слова, коды и параметры строки запроса. Пределы параметров — те же,
--- что у разбора в `tnt.admin.app.http.handlers.audit`; что они
--- не разошлись, проверяют проверки описания: запрос на пределе проходит,
--- за пределом — отказ.

local results = require('tnt.admin.app.data.results')

--- Отказ права читать журнал: у обоих путей журнала.
local FORBIDDEN_AUDIT = 'Нет права читать журнал аудита'

--- Больше номера записи журнала панель не принимает.
local LARGEST_ID = 99999999999999

--- Сколько записей проверяется за запрос, и больше не дают.
local VERIFY_BUDGET = 50000

--- Параметр строки запроса.
---@param name string
---@param description string
---@param schema table
---@return table
local function query(name, description, schema)
    return { name = name, ['in'] = 'query', description = description, schema = schema }
end

--- Номер записи журнала в строке запроса.
---@param name string
---@param description string
---@return table
local function record_id(name, description)
    return query(name, description, { type = 'integer', minimum = 1, maximum = LARGEST_ID })
end

---@param words TntAdminApiWords
---@return table<string, table>
return function(words)
    return {
        ['audit.export'] = {
            summary = 'Выгрузить журнал аудита потоком',
            description = [[
Строка на запись (NDJSON), тем же видом, что уезжает в приёмник вывоза: поля записи и
оба хеша — prev_hash и current_hash. Принявший проходит цепочку сам, не спрашивая узел:
хеш записи — sha256 от хеша предыдущей и её полей (tnt.audit.chain). Пломба (chain_seal)
— граница, оставленная очисткой, а не дыра.

Ответ идёт кусками (Transfer-Encoding: chunked), длины у него нет: в памяти узла лежит
один кусок, и медленный клиент тормозит источник. Обрыв источника посреди выгрузки рвёт
соединение без завершающего куска — обрезанная выгрузка не выглядит целой. Продолжить
оборванную — from_id на единицу больше номера последней принятой строки.

Выгрузка кончается на голове журнала, которую застала: дописанное после этого в неё не
попадает. Отбора по пользователю и времени нет намеренно: участок цепочки с дырами не
проверить, а отбирать строки из целого участка принявший умеет сам.

Читать журнал может только тот, кому приложение выдало право аудита, — право менять
кластер его не даёт. Панель без входа открыта целиком, и журнал тоже.
]],
            parameters = {
                record_id('from_id', 'С какой записи начать, включительно'),
                record_id('to_id', 'На какой закончить, включительно'),
            },
            responses = {
                [200] = {
                    description = 'Журнал кусками, строка на запись',
                    media = 'application/x-ndjson',
                    schema = { type = 'string' },
                },
                [400] = 'Участок не разобран или журнал не прочитан. Неверные аргументы названы в error.fields',
                [401] = words.unauthenticated,
                [403] = FORBIDDEN_AUDIT,
                [501] = 'Журнал аудита этой панели недоступен',
            },
        },
        ['audit.verify'] = {
            summary = 'Проверить цепочку хешей журнала аудита на узле',
            description = [[
Узел пересчитывает хеши записей подряд и сверяет ссылки. Порванная цепочка — ответ 200 с
ok: false, номером записи broken_at и причиной reason, а не отказ: проверка сделала своё
дело.

За запрос проверяется не больше budget записей. Кончился бюджет — в отчёте cursor с
after_id и hash, и следующий запрос продолжает с него теми же аргументами. Курсор значит
«бюджет кончился», а не «записи остались». Если между запросами очистка убрала запись
курсора, ответ — отказ 400: проверку надо начать заново.

Проверка не видит удаления записей с конца журнала и подмены всей цепочки целиком — для
этого есть вывоз во второе место.
]],
            parameters = {
                record_id(
                    'from_id',
                    'С какой записи начать; вместе с курсором не задаётся'
                ),
                record_id('to_id', 'На какой закончить, включительно'),
                record_id(
                    'after_id',
                    'Курсор — номер последней проверенной записи'
                ),
                query('hash', 'Курсор — её хеш; только вместе с after_id', {
                    type = 'string',
                    pattern = '^[0-9a-fA-F]+$',
                }),
                query('budget', 'Сколько записей проверить за запрос', {
                    type = 'integer',
                    minimum = 1,
                    maximum = VERIFY_BUDGET,
                    default = VERIFY_BUDGET,
                }),
            },
            responses = {
                [200] = results.AuditReport,
                [400] = 'Аргументы не разобраны или журнал не прочитан. Неверные аргументы '
                    .. 'и аргументы, противоречащие друг другу, названы в error.fields',
                [401] = words.unauthenticated,
                [403] = FORBIDDEN_AUDIT,
                [501] = 'Журнал аудита этой панели недоступен',
            },
        },
    }
end
