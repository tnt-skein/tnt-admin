--- Настройки панели: умолчания и то, что приходит из окружения.
---
--- Файл тот же, что у приложения, и читается так же: функция от
--- окружения, значения — из переменных, умолчания — рядом с именами.
--- Разница в том, что этот лежит внутри пакета и задаёт умолчания,
--- а приложение вправе положить свой `config/admin.lua` рядом со своими
--- настройками и перебить их; сильнее обоих — раздел `roles_cfg` роли
--- (`tnt.admin.app.services.settings`).
---
--- Переменной без значения здесь нет: пустое поле — это «не сказано»,
--- и поверх него ложится то, что сказал следующий.
---@param env TntEnv
return function(env)
    return {
        -- Свой порт панели: с ним она поднимает сервер сама и ни с кем
        -- его не делит. Без него встаёт на сервер `roles.httpd`.
        listen = env('ADMIN_LISTEN'),

        -- Имя сервера у `roles.httpd`, когда своего порта нет.
        -- Не `default`: там обычно стоит приложение, и молчаливое
        -- умолчание отняло бы у него обработчик.
        server = env('ADMIN_SERVER', 'admin'),

        -- Источник, установленный ради соседа, но не нужный панели,
        -- выключается переменной: выключенный она считает отсутствующим,
        -- и кнопка, которая заведомо ответила бы отказом, не появляется.
        sources = {
            snapshot = env.bool('ADMIN_SNAPSHOT'),
            issues = env.bool('ADMIN_ISSUES'),
            suggestions = env.bool('ADMIN_SUGGESTIONS'),
            filter = env.bool('ADMIN_FILTER'),
            audit = env.bool('ADMIN_AUDIT'),
            audit_verify = env.bool('ADMIN_AUDIT_VERIFY'),
            -- Толчок обзора: без него браузер обновляет страницу опросом.
            updates = env.bool('ADMIN_UPDATES'),
        },
    }
end
