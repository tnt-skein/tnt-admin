--- Роль панели: приложению остаётся назвать её в конфигурации.
---
--- Панель — не часть приложения, а второй жилец узла: она показывает сам
--- узел и кластер вокруг, и приложению о ней знать нечего. Поэтому она
--- подключается рядом, своей ролью:
---
---     roles: [roles.httpd, tnt.admin, bootstrap.app]
---
--- Панель собрана тем же фреймворком, что и приложение под ней, и лежит
--- той же раскладкой: `app/` — обработчики, слои, службы и провайдеры,
--- `routes/` — маршруты, `resources/views` — страницы,
--- `bootstrap/providers.lua` — порядок сборки. Разница одна: раскладка
--- лежит не в каталоге узла, а внутри пакета, потому что панель едет
--- роком, — и корень ей показывает `tnt.admin.app.support.root`.
---
--- Настраивается она тоже как приложение — файлом `config/admin.lua`,
--- который возвращает функцию от окружения:
---
---     -- config/admin.lua
---     ---@param env TntEnv
---     return function(env)
---         return { listen = env('ADMIN_LISTEN', '127.0.0.1:8081') }
---     end
---
--- **Порт — свой.** С `listen` панель поднимает собственный сервер и ни
--- с кем его не делит. Без `listen` она встаёт на сервер `roles.httpd`
--- по имени (`server`, по умолчанию `admin`) — для тех, кому адреса
--- и TLS удобнее держать в конфигурации кластера.
---
--- Сервер приложения панель не занимает ни в том, ни в другом случае:
--- подключение подменяет обработчик сервера целиком, и две роли
--- на одном сервере затирали бы друг друга — молча и в порядке
--- применения ролей. Отдельный порт заодно решает главное
--- в эксплуатации: панель не висит на публичном адресе, и закрывают
--- её сетью, а не одним лишь паролем.
---
--- **Чем панель питается, решает узел, а не она.** Снимок кластера,
--- находки, подсказки и журнал аудита берутся у пакетов, установленных
--- рядом (`app/services/sources.lua`); чего нет — того панель не показывает
--- и о том честно отказывает. Ни одного из этих пакетов роль не требует:
--- панель, поднятая на голом узле, отвечает и показывает пустой кластер.
---
--- Что взято, роль называет в журнале при каждом применении: умолчание
--- не должно быть молчаливым.

local framework = require('tnt.framework')

local refusals = require('tnt.admin.app.exceptions.refusal')
local root = require('tnt.admin.app.support.root')
local settings_of = require('tnt.admin.app.services.settings')
local watch = require('tnt.admin.app.services.watch')

local Module = {}

--- Имя роли: под ним же панель пишет в журнал.
Module.NAME = 'tnt.admin'

--- Роль панели, собранная фреймворком.
---
--- Здесь только имя, корень раскладки и роли ядра: остальное фреймворк
--- находит по соглашению — `bootstrap/providers.lua`, `routes/`,
--- `resources/views`. Что найдено, показывает `Module.layout()`.
---
--- Корень и приставка имён — от самого пакета: раскладка панели едет
--- роком, и путь до неё ни к рабочему каталогу узла, ни к именам модулей
--- отношения не имеет.
---@type TntFrameworkRole
local role = framework.new({
    name = Module.NAME,
    base = root.directory(),
    prefix = root.ANCHOR,
    dependencies = { 'roles.httpd' },

    -- Файлы панели едут модулем, а не каталогом: помощник `asset` ищет
    -- в `public` манифест сборки, а раздаёт панель сама — из памяти
    -- процесса, тем же роком, что и код.
    public = false,
})

--- Настройки роли для ядра: файл приложения и раздел `roles_cfg` вместе.
---
--- Ядро читает свой раздел `http` из настроек роли, а панель — из файла
--- приложения: порт, имя сервера и состав источников оператор держит
--- рядом с остальными настройками приложения. Здесь они сводятся
--- в одно, и дальше всё идёт обычным ходом ядра.
---@param cfg any Раздел `roles_cfg` роли
---@return table
local function for_kernel(cfg)
    local settings = settings_of.read(cfg)

    return settings_of.role_cfg(settings, refusals.view)
end

--- Зависимости роли — те же, что объявил фреймворк.
Module.dependencies = role.dependencies

--- Отвергает настройки, которые нельзя применить.
---@param cfg any
function Module.validate(cfg)
    role.validate(for_kernel(cfg))
end

--- Поднимает панель на её сервере.
---@param cfg any
function Module.apply(cfg)
    role.apply(for_kernel(cfg))
end

--- Снимает панель: свой сервер закрывает, чужому возвращает обработчик,
--- а обход кластера останавливает — но только свой.
function Module.stop()
    watch.stop()
    role.stop()
end

--- Что взято по соглашению о раскладке: провайдеры, страницы и маршруты
--- пакета.
Module.layout = role.layout

return Module
